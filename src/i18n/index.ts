export type TranslationKey = keyof typeof TRANSLATIONS.en;
export type Translator = (key: TranslationKey) => string;

export function createTranslator(language: PluginLanguage): Translator {
	return (key: TranslationKey): string => {
		const dictionary = TRANSLATIONS[language] ?? TRANSLATIONS.en;
		return dictionary[key] ?? TRANSLATIONS.en[key];
	};
}

export function isPluginLanguage(value: string): value is PluginLanguage {
	return value === "en" || value === "ru" || value === "es";
}

export function getLanguageLabel(language: PluginLanguage): string {
	return LANGUAGE_LABELS[language];
}

export function getSupportedLanguages(): PluginLanguage[] {
	return Object.keys(LANGUAGE_LABELS) as PluginLanguage[];
}

export function mapObsidianLanguage(languageCode: string): PluginLanguage {
	const normalized = languageCode.trim().toLowerCase();
	if (normalized.startsWith("ru")) {
		return "ru";
	}
	if (normalized.startsWith("es")) {
		return "es";
	}
	return "en";
}

export function mapPluginLanguageToSpeechLocale(language: PluginLanguage): string {
	switch (language) {
		case "ru":
			return "ru-RU";
		case "es":
			return "es-ES";
		case "en":
		default:
			return "en-US";
	}
}

export function resolvePluginLanguage(
	mode: LanguageMode,
	manualLanguage: PluginLanguage,
	obsidianLanguageCode: string,
): PluginLanguage {
	if (mode === "manual") {
		return manualLanguage;
	}
	return mapObsidianLanguage(obsidianLanguageCode);
}
